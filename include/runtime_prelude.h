#ifndef TIQ_RUNTIME_PRELUDE_H
#define TIQ_RUNTIME_PRELUDE_H

// Core Language Runtime Prelude
//
// ARCHITECTURAL BOUNDARY:
// Contains ONLY essential primitive runtime definitions, scalar types, allocation
// helpers, and slice headers required by the Tiq core language semantics.
// All auxiliary system, networking, and serialization stubs have been moved
// to `runtime_aux.h` and will be rewritten natively in Tiq (`std/*.tiq`) in M19.

static const char TIQ_CORE_RUNTIME_PRELUDE[] =
    "#if !defined(__APPLE__)\n"
    "#define _POSIX_C_SOURCE 200809L\n"
    "#endif\n"
    "#include <stdio.h>\n"
    "#include <stdlib.h>\n"
    "#include <stddef.h>\n"
    "#include <string.h>\n"
    "#include <strings.h>\n"
    "#include <stdint.h>\n"
    "#include <sys/stat.h>\n"
    "#include <sys/socket.h>\n"
    "#include <netdb.h>\n"
    "#include <netinet/in.h>\n"
    "#if defined(__APPLE__)\n"
    "#include <sys/event.h>\n"
    "#endif\n"
    "#if defined(__linux__)\n"
    "#include <sys/epoll.h>\n"
    "#endif\n"
    "#include <dirent.h>\n"
    "#include <unistd.h>\n"
    "#include <time.h>\n"
    "#include <dlfcn.h>\n"
    "typedef struct { const void *ptr; int len; } TiqSlice;\n"
    "typedef struct { int64_t value; int has_value; } TiqOption;\n"
    "typedef struct { int64_t value; int64_t error; int is_ok; } TiqResult;\n"
    "typedef enum { TIQ_ALLOC_GENERAL = 1, TIQ_ALLOC_ARENA = 2, TIQ_ALLOC_POOL = 3 } TiqAllocatorKind;\n"
    "typedef struct { TiqAllocatorKind kind; void *ctx; } TiqAllocator;\n"
    "typedef struct { unsigned char *buffer; size_t capacity; size_t offset; } TiqArena;\n"
    "typedef struct { unsigned char *buffer; uint32_t *free_list; unsigned char *in_use; size_t block_size; size_t block_count; size_t free_count; } TiqPool;\n\n"

    "static void *tiq_alloc(size_t n) {\n"
    "    void *p = malloc(n);\n"
    "    if (!p) { fprintf(stderr, \"tiq: out of memory\\n\"); exit(1); }\n"
    "    return p;\n"
    "}\n\n"

    "static int tiq_allocator_valid_alignment(size_t alignment) {\n"
    "    return alignment != 0 && (alignment & (alignment - 1)) == 0;\n"
    "}\n\n"

    "uint64_t tiq_allocator_general(void) {\n"
    "    static TiqAllocator allocator = { TIQ_ALLOC_GENERAL, NULL };\n"
    "    return (uint64_t)(uintptr_t)&allocator;\n"
    "}\n\n"

    "uint64_t tiq_arena_create(uint64_t capacity) {\n"
    "    if (capacity == 0 || capacity > (uint64_t)SIZE_MAX) return 0;\n"
    "    TiqAllocator *allocator = (TiqAllocator *)malloc(sizeof(TiqAllocator));\n"
    "    TiqArena *arena = (TiqArena *)malloc(sizeof(TiqArena));\n"
    "    unsigned char *buffer = (unsigned char *)malloc((size_t)capacity);\n"
    "    if (!allocator || !arena || !buffer) { free(buffer); free(arena); free(allocator); return 0; }\n"
    "    arena->buffer = buffer;\n"
    "    arena->capacity = (size_t)capacity;\n"
    "    arena->offset = 0;\n"
    "    allocator->kind = TIQ_ALLOC_ARENA;\n"
    "    allocator->ctx = arena;\n"
    "    return (uint64_t)(uintptr_t)allocator;\n"
    "}\n\n"

    "uint64_t tiq_pool_create(uint64_t block_size, uint64_t block_count) {\n"
    "    if (block_size == 0 || block_count == 0) return 0;\n"
    "    if (block_size > (uint64_t)SIZE_MAX || block_count > (uint64_t)SIZE_MAX) return 0;\n"
    "    if ((size_t)block_count > SIZE_MAX / (size_t)block_size) return 0;\n"
    "    if ((size_t)block_count > SIZE_MAX / sizeof(uint32_t)) return 0;\n"
    "    if (block_count > UINT32_MAX) return 0;\n"
    "    TiqAllocator *allocator = (TiqAllocator *)malloc(sizeof(TiqAllocator));\n"
    "    TiqPool *pool = (TiqPool *)malloc(sizeof(TiqPool));\n"
    "    unsigned char *buffer = (unsigned char *)malloc((size_t)block_size * (size_t)block_count);\n"
    "    uint32_t *free_list = (uint32_t *)malloc(sizeof(uint32_t) * (size_t)block_count);\n"
    "    unsigned char *in_use = (unsigned char *)calloc((size_t)block_count, 1);\n"
    "    if (!allocator || !pool || !buffer || !free_list || !in_use) {\n"
    "        free(in_use); free(free_list); free(buffer); free(pool); free(allocator); return 0;\n"
    "    }\n"
    "    for (size_t i = 0; i < (size_t)block_count; i++) free_list[i] = (uint32_t)((size_t)block_count - i - 1);\n"
    "    pool->buffer = buffer;\n"
    "    pool->free_list = free_list;\n"
    "    pool->in_use = in_use;\n"
    "    pool->block_size = (size_t)block_size;\n"
    "    pool->block_count = (size_t)block_count;\n"
    "    pool->free_count = (size_t)block_count;\n"
    "    allocator->kind = TIQ_ALLOC_POOL;\n"
    "    allocator->ctx = pool;\n"
    "    return (uint64_t)(uintptr_t)allocator;\n"
    "}\n\n"

    "uint64_t tiq_allocator_alloc(uint64_t handle, uint64_t size, uint64_t alignment) {\n"
    "    if (handle == 0 || size == 0 || size > (uint64_t)SIZE_MAX || alignment > (uint64_t)SIZE_MAX) return 0;\n"
    "    size_t n = (size_t)size;\n"
    "    size_t a = (size_t)alignment;\n"
    "    if (!tiq_allocator_valid_alignment(a)) return 0;\n"
    "    TiqAllocator *allocator = (TiqAllocator *)(uintptr_t)handle;\n"
    "    if (allocator->kind == TIQ_ALLOC_GENERAL) {\n"
    "        if (a > _Alignof(max_align_t)) return 0;\n"
    "        return (uint64_t)(uintptr_t)malloc(n);\n"
    "    }\n"
    "    if (allocator->kind == TIQ_ALLOC_ARENA) {\n"
    "        TiqArena *arena = (TiqArena *)allocator->ctx;\n"
    "        if (!arena || arena->offset > SIZE_MAX - (a - 1)) return 0;\n"
    "        size_t start = (arena->offset + (a - 1)) & ~(a - 1);\n"
    "        if (start > arena->capacity || n > arena->capacity - start) return 0;\n"
    "        arena->offset = start + n;\n"
    "        return (uint64_t)(uintptr_t)(arena->buffer + start);\n"
    "    }\n"
    "    if (allocator->kind == TIQ_ALLOC_POOL) {\n"
    "        TiqPool *pool = (TiqPool *)allocator->ctx;\n"
    "        if (!pool || n > pool->block_size || a > _Alignof(max_align_t) || pool->free_count == 0) return 0;\n"
    "        uint32_t index = pool->free_list[--pool->free_count];\n"
    "        pool->in_use[index] = 1;\n"
    "        return (uint64_t)(uintptr_t)(pool->buffer + (size_t)index * pool->block_size);\n"
    "    }\n"
    "    return 0;\n"
    "}\n\n"

    "int64_t tiq_allocator_dealloc(uint64_t handle, uint64_t ptr, uint64_t size, uint64_t alignment) {\n"
    "    (void)size;\n"
    "    if (handle == 0 || ptr == 0 || alignment > (uint64_t)SIZE_MAX) return -1;\n"
    "    size_t a = (size_t)alignment;\n"
    "    if (!tiq_allocator_valid_alignment(a)) return -1;\n"
    "    TiqAllocator *allocator = (TiqAllocator *)(uintptr_t)handle;\n"
    "    if (allocator->kind == TIQ_ALLOC_GENERAL) { free((void *)(uintptr_t)ptr); return 0; }\n"
    "    if (allocator->kind == TIQ_ALLOC_ARENA) return 0;\n"
    "    if (allocator->kind == TIQ_ALLOC_POOL) {\n"
    "        TiqPool *pool = (TiqPool *)allocator->ctx;\n"
    "        if (!pool) return -1;\n"
    "        uintptr_t begin = (uintptr_t)pool->buffer;\n"
    "        uintptr_t end = begin + pool->block_size * pool->block_count;\n"
    "        uintptr_t p = (uintptr_t)ptr;\n"
    "        if (p < begin || p >= end) return -1;\n"
    "        size_t delta = (size_t)(p - begin);\n"
    "        if (delta % pool->block_size != 0) return -1;\n"
    "        size_t index = delta / pool->block_size;\n"
    "        if (index >= pool->block_count || pool->in_use[index] == 0 || pool->free_count >= pool->block_count) return -1;\n"
    "        pool->in_use[index] = 0;\n"
    "        pool->free_list[pool->free_count++] = (uint32_t)index;\n"
    "        return 0;\n"
    "    }\n"
    "    return -1;\n"
    "}\n\n"

    "int64_t tiq_allocator_reset(uint64_t handle) {\n"
    "    if (handle == 0) return -1;\n"
    "    TiqAllocator *allocator = (TiqAllocator *)(uintptr_t)handle;\n"
    "    if (allocator->kind == TIQ_ALLOC_GENERAL) return 0;\n"
    "    if (allocator->kind == TIQ_ALLOC_ARENA) {\n"
    "        TiqArena *arena = (TiqArena *)allocator->ctx;\n"
    "        if (!arena) return -1;\n"
    "        arena->offset = 0;\n"
    "        return 0;\n"
    "    }\n"
    "    if (allocator->kind == TIQ_ALLOC_POOL) {\n"
    "        TiqPool *pool = (TiqPool *)allocator->ctx;\n"
    "        if (!pool) return -1;\n"
    "        memset(pool->in_use, 0, pool->block_count);\n"
    "        for (size_t i = 0; i < pool->block_count; i++) pool->free_list[i] = (uint32_t)(pool->block_count - i - 1);\n"
    "        pool->free_count = pool->block_count;\n"
    "        return 0;\n"
    "    }\n"
    "    return -1;\n"
    "}\n\n"

    "int64_t tiq_allocator_destroy(uint64_t handle) {\n"
    "    if (handle == 0) return -1;\n"
    "    TiqAllocator *allocator = (TiqAllocator *)(uintptr_t)handle;\n"
    "    if (allocator->kind == TIQ_ALLOC_GENERAL) return 0;\n"
    "    if (allocator->kind == TIQ_ALLOC_ARENA) {\n"
    "        TiqArena *arena = (TiqArena *)allocator->ctx;\n"
    "        if (!arena) return -1;\n"
    "        free(arena->buffer);\n"
    "        free(arena);\n"
    "        free(allocator);\n"
    "        return 0;\n"
    "    }\n"
    "    if (allocator->kind == TIQ_ALLOC_POOL) {\n"
    "        TiqPool *pool = (TiqPool *)allocator->ctx;\n"
    "        if (!pool) return -1;\n"
    "        free(pool->in_use);\n"
    "        free(pool->free_list);\n"
    "        free(pool->buffer);\n"
    "        free(pool);\n"
    "        free(allocator);\n"
    "        return 0;\n"
    "    }\n"
    "    return -1;\n"
    "}\n\n"

    "static const char *tiq_str_dup(const char *s) {\n"
    "    size_t n = strlen(s);\n"
    "    char *b = (char *)tiq_alloc(n + 1);\n"
    "    memcpy(b, s, n + 1);\n"
    "    return b;\n"
    "}\n\n"

    "static int64_t tiq_argc = 0;\n"
    "static char **tiq_argv = 0;\n\n";

#endif
